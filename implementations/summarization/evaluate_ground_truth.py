"""Evaluate ground truth summaries using the evaluation harness.

This script creates a Langfuse experiment that evaluates the ground truth summaries
(description field) as if they were agent outputs. This creates a baseline for
comparison with actual agent performance.

Usage:
    python evaluate_ground_truth.py --dataset-name "Financial-News-Summarization"
"""

import asyncio
import logging
from typing import Any

import click
from aieng.agent_evals.async_client_manager import AsyncClientManager
from aieng.agent_evals.evaluation import run_experiment
from aieng.agent_evals.evaluation.graders.config import LLMRequestConfig
from aieng.agent_evals.logging_config import setup_logging
from aieng.agent_evals.summarization.summarization_grader import (
    SummarizationResult,
    evaluate_summarization_async,
)
from dotenv import load_dotenv
from langfuse.experiment import Evaluation, ExperimentResult


load_dotenv(verbose=True)
setup_logging(level=logging.INFO, show_time=True, show_path=False)
logger = logging.getLogger(__name__)


DEFAULT_DATASET_NAME = "Financial-News-Summarization"
DEFAULT_EXPERIMENT_NAME = "Ground Truth Baseline Evaluation"


async def ground_truth_task(*, item: Any, **kwargs: Any) -> str:  # noqa: ARG001
    """Return the ground truth summary as if it were agent output.

    Parameters
    ----------
    item : Any
        The Langfuse experiment item containing the article data.
    **kwargs : Any
        Additional arguments from the harness (unused).

    Returns
    -------
    str
        The ground truth summary (expected_output) returned as "agent" output.
    """
    # Simply return the ground truth summary as if it were generated by an agent
    ground_truth_summary = item.expected_output
    
    # Extract article data for logging
    if hasattr(item, 'input') and isinstance(item.input, dict):
        article_data = item.input
    elif isinstance(item, dict):
        article_data = item
    else:
        article_data = {}
    
    title = article_data.get("title", "")
    logger.info(f"Using ground truth for: {title[:80]}...")
    
    # Attach metadata to show this is ground truth
    client_manager = AsyncClientManager.get_instance()
    client_manager.langfuse_client.update_current_span(
        metadata={
            "is_ground_truth": True,
            "article_title": title[:100],
            "summary_length": len(ground_truth_summary),
            "note": "This is ground truth summary being evaluated as baseline",
        }
    )
    
    return ground_truth_summary


async def summarization_evaluator(
    *,
    input: Any,  # noqa: A002
    output: str,
    expected_output: str,
    metadata: dict[str, Any] | None = None,
    **kwargs: Any,  # noqa: ARG001
) -> list[Evaluation]:
    """Evaluate the summary using LLM-as-a-judge methodology.

    Parameters
    ----------
    input : Any
        The original article data (title and body).
    output : str
        The "agent's" generated summary (actually ground truth in this case).
    expected_output : str
        The ground truth summary (same as output in this baseline test).
    metadata : dict[str, Any] | None, optional
        Item metadata (unused for summarization).
    **kwargs : Any
        Additional arguments from the harness (unused).

    Returns
    -------
    list[Evaluation]
        List of Langfuse Evaluations with accuracy, completeness, conciseness,
        clarity, average score, and overall quality assessments.
    """
    # Extract article data
    if isinstance(input, dict):
        title = input.get("title", "")
        maintext = input.get("maintext", "")
    else:
        title = ""
        maintext = str(input) if input else ""
    
    logger.info(f"Evaluating ground truth summary for: {title[:50]}...")

    try:
        # Evaluate the ground truth summary
        result = await evaluate_summarization_async(
            title=title,
            body=maintext,
            summary=str(output),
            model_config=LLMRequestConfig(temperature=0.0),
        )

        evaluations = result.to_evaluations()
        logger.info(f"Ground truth evaluation: {result.overall_quality.value} (avg: {result.average_score:.2f})")
        return evaluations

    except Exception as e:
        logger.error(f"Evaluation failed: {e}")
        return SummarizationResult.error_evaluations(str(e))


async def run_ground_truth_evaluation(
    dataset_name: str,
    experiment_name: str,
    max_concurrency: int = 1,
) -> ExperimentResult:
    """Run the ground truth baseline evaluation experiment.

    Parameters
    ----------
    dataset_name : str
        Name of the Langfuse dataset to evaluate against.
    experiment_name : str
        Name for this experiment run.
    max_concurrency : int, optional
        Maximum concurrent evaluations, by default 1.
    """
    client_manager = AsyncClientManager.get_instance()

    try:
        logger.info(f"Starting ground truth baseline experiment '{experiment_name}' on dataset '{dataset_name}'")
        logger.info(f"Max concurrency: {max_concurrency}")

        # Run experiment using ground truth as "agent" output
        result = run_experiment(
            dataset_name=dataset_name,
            name=experiment_name,
            description="Baseline evaluation using ground truth summaries as agent output",
            task=ground_truth_task,
            evaluators=[summarization_evaluator],
            max_concurrency=max_concurrency,
        )

        logger.info("Ground truth baseline experiment complete!")
        logger.info(f"Results: {result}")

        return result

    finally:
        logger.info("Closing client manager and flushing data...")
        try:
            await client_manager.close()
            await asyncio.sleep(0.1)
            logger.info("Cleanup complete")
        except Exception as e:
            logger.warning(f"Cleanup warning: {e}")


@click.command()
@click.option(
    "--dataset-name",
    default=DEFAULT_DATASET_NAME,
    help="Name of the Langfuse dataset to evaluate against.",
)
@click.option(
    "--experiment-name",
    default=DEFAULT_EXPERIMENT_NAME,
    help="Name for this experiment run.",
)
@click.option(
    "--max-concurrency",
    default=1,
    type=int,
    help="Maximum concurrent evaluations (default: 1).",
)
def cli(dataset_name: str, experiment_name: str, max_concurrency: int) -> None:
    """Run ground truth baseline evaluation using Langfuse experiments."""
    asyncio.run(
        run_ground_truth_evaluation(
            dataset_name,
            experiment_name,
            max_concurrency,
        )
    )


if __name__ == "__main__":
    cli()